import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { generateTypeScriptClient } from './client-generator.mjs'

export function integrationManifest(project) {
  return {
    version: 'lacify.dev/integration/v1',
    project: project.project.runtime.project,
    projectFingerprint: project.fingerprint,
    generatedClient: 'generated/lacify/client.ts',
    serverAdapter: 'generated/lacify/server.ts',
    requiredEnvironment: [
      { name: 'LACIFY_RUNTIME_URL', secret: false, scope: 'server-only' },
      { name: 'LACIFY_RUNTIME_TOKEN', secret: true, scope: 'server-only' },
    ],
    actors: project.project.actors.map(({ definition, operations }) => ({
      name: definition.name,
      operations: operations.map(({ definition: operation }) => ({
        name: operation.name,
        kind: operation.kind,
      })),
    })),
  }
}

export function renderServerAdapter(project) {
  return `// Generated by Lacify for project fingerprint ${project.fingerprint}. Do not edit.
import { LacifyClient } from './client.js'

export interface LacifyServerEnvironment {
  LACIFY_RUNTIME_URL?: string
  LACIFY_RUNTIME_TOKEN?: string
}

function required(name: keyof LacifyServerEnvironment, value: string | undefined): string {
  if (!value) throw new Error(\`\${name} is required in the trusted server environment.\`)
  return value
}

export function createLacifyServerClient(environment: LacifyServerEnvironment, fetchImpl: typeof fetch = fetch): LacifyClient {
  const rawUrl = required('LACIFY_RUNTIME_URL', environment.LACIFY_RUNTIME_URL)
  const token = required('LACIFY_RUNTIME_TOKEN', environment.LACIFY_RUNTIME_TOKEN)
  const url = new URL(rawUrl)
  const local = url.protocol === 'http:' && (url.hostname === '127.0.0.1' || url.hostname === 'localhost')
  if (url.protocol !== 'https:' && !local) throw new Error('LACIFY_RUNTIME_URL must use HTTPS except for localhost development.')
  if (!/^lacify_runtime_[A-Za-z0-9_-]{40,100}$/.test(token)) throw new Error('LACIFY_RUNTIME_TOKEN is not a valid scoped runtime credential.')
  return new LacifyClient(url.toString().replace(/\\/$/, ''), token, fetchImpl)
}
`
}

export async function generateIntegration(project, root) {
  const outputDirectory = path.join(root, 'generated', 'lacify')
  const client = await generateTypeScriptClient(project, outputDirectory)
  const adapter = path.join(outputDirectory, 'server.ts')
  const manifestFile = path.join(root, '.lacify', 'integration.json')
  await mkdir(path.dirname(manifestFile), { recursive: true })
  await writeFile(adapter, renderServerAdapter(project))
  await writeFile(manifestFile, `${JSON.stringify(integrationManifest(project), null, 2)}\n`, { mode: 0o600 })
  return { client, adapter, manifest: manifestFile }
}
