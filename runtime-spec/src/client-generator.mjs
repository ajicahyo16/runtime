import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

function camelCase(value) {
  return value.charAt(0).toLowerCase() + value.slice(1)
}

function typeScriptType(type) {
  if (type === 'integer' || type === 'number') return 'number'
  if (type === 'boolean') return 'boolean'
  return 'string'
}

function operationResultType(actorName, operation) {
  if (operation.result.mode === 'none') return 'null'
  const row = `${actorName}${operation.name}Row`
  if (operation.result.mode === 'one') return row
  if (operation.result.mode === 'optional') return `${row} | null`
  return operation.result.pagination ? `LacifyPage<${row}>` : `${row}[]`
}

export function renderTypeScriptClient(loadedProject) {
  const project = loadedProject.project.runtime.project
  const actors = loadedProject.project.actors
  const actorTypes = actors.map(({ definition }) => {
    const commands = definition.commands.map((command) => JSON.stringify(command)).join(' | ')
    return `export type ${definition.name}Command = ${commands}`
  }).join('\n')
  const operationTypes = actors.flatMap(({ definition, operations = [] }) => operations.flatMap(({ definition: operation }) => {
    const fields = Object.entries(operation.input).map(([name, field]) => `  ${name}${field.required ? '' : '?'}: ${typeScriptType(field.type)}`).join('\n')
    const input = `export interface ${definition.name}${operation.name}Input {\n${fields}\n}`
    if (operation.result.mode === 'none') return [input]
    const resultFields = Object.entries(operation.result.fields || {}).map(([name, field]) => `  ${name}: ${typeScriptType(field.type)}${field.nullable ? ' | null' : ''}`).join('\n')
    return [input, `export interface ${definition.name}${operation.name}Row {\n${resultFields}\n}`]
  })).join('\n')
  const clients = actors.map(({ definition, operations = [] }) => {
    const operationMethods = operations.map(({ definition: operation }) => {
      const inputType = `${definition.name}${operation.name}Input`
      const resultType = operationResultType(definition.name, operation)
      if (operation.kind === 'command') {
        return `      ${camelCase(operation.name)}: (input: ${inputType}, options: { idempotencyKey?: string } = {}) =>
        this.commandOperation<${resultType}>(${JSON.stringify(definition.name)}, partition, ${JSON.stringify(operation.name)}, input, options.idempotencyKey),`
      }
      if (operation.result.pagination) {
        return `      ${camelCase(operation.name)}: (input: ${inputType}, page: LacifyPageRequest = {}) =>
        this.queryOperation<${resultType}>(${JSON.stringify(definition.name)}, partition, ${JSON.stringify(operation.name)}, input, page),`
      }
      return `      ${camelCase(operation.name)}: (input: ${inputType}) =>
        this.queryOperation<${resultType}>(${JSON.stringify(definition.name)}, partition, ${JSON.stringify(operation.name)}, input),`
    }).join('\n')
    return `
  ${camelCase(definition.name)}(partition: string) {
    return {
      command: <TResponse = unknown>(command: ${definition.name}Command, input: JsonObject = {}) =>
        this.request<TResponse>(${JSON.stringify(definition.name)}, partition, command, input),
${operationMethods}
    }
  }`
  }).join('\n')
  return `// Generated by Lacify from project fingerprint ${loadedProject.fingerprint}. Do not edit.
export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue }
export type JsonObject = { [key: string]: JsonValue }
export interface LacifyOperationResponse<T> { success: true; operation: string; partitionId: string; data: T }
export interface LacifyCommandResponse<T> extends LacifyOperationResponse<T> { command: string; state: string; version: number; lifecycle: string[]; eventId: string; replayed?: boolean }
export interface LacifyPageRequest { cursor?: string | null; pageSize?: number }
export interface LacifyPage<T> { items: T[]; nextCursor: string | null }
export class LacifyRuntimeError extends Error {
  constructor(
    public readonly status: number,
    public readonly code: string,
    message: string,
    public readonly retryable: boolean,
  ) {
    super(message)
    this.name = 'LacifyRuntimeError'
  }
}
${actorTypes}
${operationTypes}

export class LacifyClient {
  constructor(
    private readonly baseUrl: string,
    private readonly accessToken: string,
    private readonly fetchImpl: typeof fetch = fetch,
  ) {}

  private headers(extra: Record<string, string> = {}): Record<string, string> {
    return { 'content-type': 'application/json', authorization: \`Bearer \${this.accessToken}\`, ...extra }
  }

  private async failure(response: Response, fallback: string): Promise<LacifyRuntimeError> {
    const body = await response.clone().json().catch(() => null) as { error?: { code?: string; message?: string } } | null
    const code = body?.error?.code || 'runtime_request_failed'
    const message = body?.error?.message || \`\${fallback} with HTTP \${response.status}.\`
    return new LacifyRuntimeError(
      response.status,
      code,
      message,
      response.status === 429 || response.status >= 500,
    )
  }

  private async request<T>(actor: string, partition: string, command: string, input: JsonObject): Promise<T> {
    const collection = \`\${actor.toLowerCase()}s\`
    const response = await this.fetchImpl(\`\${this.baseUrl}/v1/\${collection}/\${encodeURIComponent(partition)}/commands\`, {
      method: 'POST',
      headers: this.headers(),
      body: JSON.stringify({ command, payload: input }),
    })
    if (!response.ok) throw await this.failure(response, 'Lacify command failed')
    return response.json() as Promise<T>
  }

  private async commandOperation<T>(actor: string, partition: string, operation: string, input: object, idempotencyKey?: string): Promise<LacifyCommandResponse<T>> {
    const collection = \`\${actor.toLowerCase()}s\`
    const response = await this.fetchImpl(\`\${this.baseUrl}/v1/\${collection}/\${encodeURIComponent(partition)}/commands\`, {
      method: 'POST',
      headers: this.headers(idempotencyKey ? { 'idempotency-key': idempotencyKey } : {}),
      body: JSON.stringify({ command: operation, payload: input }),
    })
    if (!response.ok) throw await this.failure(response, 'Lacify operation failed')
    return response.json() as Promise<LacifyCommandResponse<T>>
  }

  private async queryOperation<T>(actor: string, partition: string, operation: string, input: object, page?: LacifyPageRequest): Promise<LacifyOperationResponse<T>> {
    const collection = \`\${actor.toLowerCase()}s\`
    const response = await this.fetchImpl(\`\${this.baseUrl}/v1/\${collection}/\${encodeURIComponent(partition)}/queries/\${encodeURIComponent(operation)}\`, {
      method: 'POST',
      headers: this.headers(),
      body: JSON.stringify({ input, ...(page ? { page } : {}) }),
    })
    if (!response.ok) throw await this.failure(response, 'Lacify query failed')
    return response.json() as Promise<LacifyOperationResponse<T>>
  }
${clients}
}

export const lacifyProject = ${JSON.stringify({ project, fingerprint: loadedProject.fingerprint, actors: actors.map(({ definition }) => definition.name) }, null, 2)} as const
`
}

export async function generateTypeScriptClient(loadedProject, outputDirectory) {
  await mkdir(outputDirectory, { recursive: true })
  const file = path.join(outputDirectory, 'client.ts')
  await writeFile(file, renderTypeScriptClient(loadedProject))
  return file
}
